export type MsgId = keyof typeof en

const TABLES: Record<Locale, Record<MsgId, string>> = { en, es }

export function t(
  locale: Locale,
  id: MsgId,
  vars?: Record<string, string | number>,
): string {
  let text = TABLES[locale][id] ?? TABLES.en[id]
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${key}}`, String(value))
    }
  }
  return text
}

export function mealLabel(locale: Locale, meal: MealType): string {
  if (meal === 'Breakfast') return t(locale, 'mealBreakfast')
  if (meal === 'Lunch') return t(locale, 'mealLunch')
  if (meal === 'Dinner') return t(locale, 'mealDinner')
  return t(locale, 'mealSnack')
}

export function goalLabel(locale: Locale, goal: Goal): string {
  if (goal === 'lose') return t(locale, 'goalLose')
  if (goal === 'gain') return t(locale, 'goalGain')
  return t(locale, 'goalMaintain')
}

export function activityCopy(
  locale: Locale,
  activity: ActivityLevel,
): { label: string; hint: string } {
  const map: Record<ActivityLevel, { label: MsgId; hint: MsgId }> = {
    sedentary: { label: 'actSedentary', hint: 'actSedentaryHint' },
    light: { label: 'actLight', hint: 'actLightHint' },
    moderate: { label: 'actModerate', hint: 'actModerateHint' },
    active: { label: 'actActive', hint: 'actActiveHint' },
    very_active: { label: 'actVeryActive', hint: 'actVeryActiveHint' },
  }
  const ids = map[activity]
  return { label: t(locale, ids.label), hint: t(locale, ids.hint) }
}

export function cuisineName(
  locale: Locale,
  cuisine: 'mexican' | 'american' | 'italian' | 'chinese',
): string {
  if (cuisine === 'mexican') return t(locale, 'cuisineMexican')
  if (cuisine === 'american') return t(locale, 'cuisineAmerican')
  if (cuisine === 'italian') return t(locale, 'cuisineItalian')
  return t(locale, 'cuisineChinese')
}

export function categoryLabel(locale: Locale, category: string): string {
  const key = `cat_${category.replace(/-/g, '_')}` as MsgId
  if (key in TABLES.en) return t(locale, key)
  return category.replace(/-/g, ' ')
}

