export function ingredientUnit(id: string): NonNullable<Ingredient['unit']> {
  return id in LIQUID_DENSITY ? 'ml' : 'g'
}

export function ingredientDensity(id: string): number {
  return LIQUID_DENSITY[id] ?? 1
}

export function getIngredient(id: string): Ingredient | undefined {
  const ing = byId.get(id)
  if (!ing) return undefined
  const unit = ingredientUnit(id)
  return {
    ...ing,
    unit,
    density: unit === 'ml' ? ingredientDensity(id) : undefined,
  }
}

export function requireIngredient(id: string): Ingredient {
  const ing = getIngredient(id)
  if (!ing) throw new Error(`Unknown ingredient: ${id}`)
  return ing
}
